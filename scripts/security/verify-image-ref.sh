#!/bin/sh
set -eu

image=${1:-}
case "$image" in
  *@sha256:????????????????????????????????????????????????????????????????) ;;
  *)
    printf '%s\n' 'image must use an immutable sha256 digest' >&2
    exit 64
    ;;
esac
case "$image" in
  *[!A-Za-z0-9._/:@+-]*)
    printf '%s\n' 'invalid image reference' >&2
    exit 64
    ;;
esac
digest=${image##*@sha256:}
case "$digest" in
  *[!a-fA-F0-9]*)
    printf '%s\n' 'invalid sha256 digest' >&2
    exit 64
    ;;
esac
printf '%s\n' "$image"
